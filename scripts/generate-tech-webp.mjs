fs.mkdirSync(outDir, { recursive: true });

async function writeIcon(slug, hex, svg) {
  const colored = svg.replace(/<path /g, `<path fill="#${hex}" `);
  const iconLayer = await sharp(Buffer.from(colored))
    .resize(ICON_PX, ICON_PX, {
      fit: "contain",
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .png()
    .toBuffer();
  const outPath = path.join(outDir, `${slug}.webp`);
  await sharp({
    create: {
      width: SIZE,
      height: SIZE,
      channels: 4,
      background: TILE_BG,
    },
  })
    .composite([{ input: iconLayer, gravity: "center" }])
    .webp({ quality: 92 })
    .toFile(outPath);
  return slug;
}

const slugs = [];

for (const { slug, hex, svg } of CUSTOM_ICONS) {
  slugs.push(await writeIcon(slug, hex, svg));
  console.log("wrote", slug + ".webp");
}

for (const key of ICON_KEYS) {
  const icon = si[key];
  if (!icon) {
    console.warn("Missing icon:", key);
    continue;
  }
  slugs.push(await writeIcon(icon.slug, icon.hex, icon.svg));
  console.log("wrote", icon.slug + ".webp");
}

